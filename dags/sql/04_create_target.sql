    AIRPORT_SK STRING DEFAULT UUID_STRING(),
    AIRPORT_NAME STRING,
    AIRPORT_COUNTRY_CODE STRING,
    COUNTRY_NAME STRING,
    AIRPORT_CONTINENT STRING,
    CONTINENT_NAME STRING,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

