CREATE TABLE IF NOT EXISTS AIRLINE_DWH.TARGET_DWH.DIM_PASSENGER (
    PASSENGER_SK STRING, 
    PASSENGER_ID STRING,
    FIRST_NAME STRING,
    LAST_NAME STRING,
    GENDER STRING,
    NATIONALITY STRING,
    -- 
    VALID_FROM TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

